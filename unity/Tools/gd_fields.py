"""Turn the top-level var / const declarations of a GDScript file into C# fields (for the Unity port).
Usage: python unity/Tools/gd_fields.py godot/scripts/bike/bike_physics.gd > out.cs
Skips test switches (_OLD_*, *_PROBE, Env reads). Prints what it can't type as `// TODO` lines.
"""
import re, sys

SKIP = re.compile(r'^_?OLD_|_OLD_|PROBE|^_E|^_eb|^_jp|^_wr_old|^_HEAT_HOLD|^bank_probe|^_crash_log|^_BOB|^_bob|^_SD_|^_AIRSTEER|^_PULL_PROBE|^WEAVE_ON|^_wg_init')

def split_top(s):
    """split a line on ';' outside brackets / strings"""
    out, depth, cur, q = [], 0, '', None
    for ch in s:
        if q:
            cur += ch
            if ch == q: q = None
            continue
        if ch in '"\'': q = ch
        if ch in '([{': depth += 1
        if ch in ')]}': depth -= 1
        if ch == ';' and depth == 0:
            out.append(cur); cur = ''
        else:
            cur += ch
    out.append(cur)
    return out

def strip_comment(s):
    q = None
    for i, ch in enumerate(s):
        if q:
            if ch == q: q = None
            continue
        if ch in '"\'': q = ch
        elif ch == '#': return s[:i], s[i + 1:].strip()
    return s, ''

def num(v):
    v = v.strip()
    if v in ('NAN',): return 'double.NaN'
    if v in ('INF',): return 'double.PositiveInfinity'
    if v in ('-INF',): return 'double.NegativeInfinity'
    return v

def cs_value(val, decl_type):
    val = val.strip()
    if decl_type:
        t = decl_type.strip()
        m = {'float': 'double', 'int': 'int', 'bool': 'bool', 'String': 'string', 'Vector2': 'V2', 'Vector3': 'V3'}.get(t)
        if m: return m, conv_expr(val, m)
        if t.startswith('Array[Vector3]'): return 'V3[]', 'new V3[] ' + conv_array(val, 'V3')
        if t.startswith('Array'): return 'List<double>', 'new List<double>()' if val in ('[]', '') else 'new List<double> ' + conv_array(val, 'double')
        if t == 'Dictionary': return 'Dictionary<string, double>', 'new Dictionary<string, double>()'
        return None, None
    if val in ('true', 'false'): return 'bool', val
    if val.startswith('"'): return 'string', val
    if val in ('NAN', 'INF', '-INF') or re.fullmatch(r'-?\d+\.\d*(e-?\d+)?|-?\d*\.\d+(e-?\d+)?|-?\d+e-?\d+', val): return 'double', num(val)
    if re.fullmatch(r'-?\d+', val): return 'int', val
    if val == 'Vector2.ZERO': return 'V2', 'V2.Zero'
    if val == 'Vector3.ZERO': return 'V3', 'V3.Zero'
    if val.startswith('Vector2('): return 'V2', 'new V2' + val[7:]
    if val.startswith('Vector3('): return 'V3', 'new V3' + val[7:]
    if val == '{}': return 'Dictionary<string, double>', 'new Dictionary<string, double>()'
    if val == '[]': return 'List<double>', 'new List<double>()'
    if val.startswith('['):
        inner = val[1:-1]
        if '"' in inner: return 'string[]', 'new string[] {' + inner + '}'
        if 'Vector' in inner: return None, None
        return 'double[]', 'new double[] {' + inner + '}'
    if val == 'PackedFloat64Array()': return 'double[]', 'new double[0]'
    if val == 'PackedFloat32Array()': return 'double[]', 'new double[11]'
    if val == 'null': return 'object', 'null'
    if re.fullmatch(r'[A-Z_][A-Z0-9_]*', val): return 'double', val   # another const
    return None, None

def conv_expr(val, t):
    if t == 'double': return num(val)
    if t == 'V2' and val.startswith('Vector2('): return 'new V2' + val[7:]
    if t == 'V3' and val.startswith('Vector3('): return 'new V3' + val[7:]
    return val

def conv_array(val, t):
    inner = val.strip()[1:-1]
    if t == 'V3': inner = inner.replace('Vector3(', 'new V3(')
    return '{' + inner + '}'

def main(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    seen = set()
    print('// GENERATED by unity/Tools/gd_fields.py from ' + path.replace('\\', '/') + ' - edit the port by hand after this.')
    for ln in lines:
        if not re.match(r'^(static )?(var|const) ', ln): continue
        code, comment = strip_comment(ln)
        for part in split_top(code):
            part = part.strip()
            m = re.match(r'^(static )?(var|const)\s+([A-Za-z_][A-Za-z0-9_]*)\s*(:\s*([A-Za-z0-9_\[\]]+))?\s*(:?=)\s*(.*)$', part)
            if not m:
                if part: print('// TODO ' + part)
                continue
            static, kind, name, _, dtype, _, val = m.groups()
            if SKIP.search(name) or 'Env.' in val or name in seen: continue
            seen.add(name)
            t, v = cs_value(val, dtype)
            c = ('  // ' + comment) if comment else ''
            if t is None:
                print(f'    // TODO {kind} {name} = {val}{c}')
                continue
            if kind == 'const':
                if t in ('double', 'int', 'bool', 'string'): print(f'    public const {t} {name} = {v};{c}')
                else: print(f'    public static readonly {t} {name} = {v};{c}')
            else:
                print(f'    public {"static " if static else ""}{t} {name} = {v};{c}')

if __name__ == '__main__':
    main(sys.argv[1])
