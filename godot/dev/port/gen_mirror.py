"""Writes the state mirror between the GDScript BikePhysics (what the game holds and reads at full GDScript speed) and the
C# BikeSim (what steps): every number / bool / int member in one packed array, the same slot on both sides.

  scripts/bike/bike_mirror.gd        BikeMirror.pack(ph) / unpack(ph, a)   (GDScript, typed member access)
  scripts/bike/BikePhysicsCs.gen.cs  BikePhysicsCs.Unpack(a) / Pack()      (C#)

python godot/dev/port/gen_mirror.py   (after gd2cs.py wrote dev/port/out/members.json: bash godot/dev/port/gen.sh)
"""
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
m = json.load(open(os.path.join(ROOT, "dev/port/out/members.json")))
KEYWORDS = {"base", "lock", "object", "string", "params", "out", "ref", "in", "is", "as", "new", "this", "case", "char",
            "decimal", "default", "delegate", "event", "fixed", "checked", "operator", "internal", "goto", "implicit",
            "explicit", "namespace", "using", "struct", "sizeof", "typeof", "unchecked", "unsafe", "virtual", "volatile",
            "void", "float", "double", "int", "long", "short", "byte", "uint", "ulong", "readonly", "sealed", "stackalloc",
            "switch", "throw", "try", "catch", "finally", "abstract", "const", "continue", "do", "else", "enum", "extern",
            "false", "for", "foreach", "if", "interface", "null", "override", "private", "protected", "public", "return",
            "static", "true", "while", "class", "bool", "break"}
# members kept apart: engine links / config set once by setup() / scratch / probes (see BikePhysicsCs.cs)
SKIP = {"_wg_init"}
# GDScript `static var`s (constant test flags read once) are not reached through an instance: left out
import re
SRC = open(os.path.join(ROOT, "scripts/bike/bike_physics.gd"), encoding="utf-8").read()
SKIP |= set(re.findall(r"^static var (\w+)", SRC, re.M))

slots = []   # (gd expr, cs expr, kind)
for name, t in m["members"].items():
    if name in SKIP:
        continue
    cs = "@" + name if name in KEYWORDS else name
    if t in ("double", "long", "bool"):
        slots.append((name, cs, t))
    elif t == "V2":
        slots.append((name + ".x", cs + ".x", "double"))
        slots.append((name + ".y", cs + ".y", "double"))
N = len(slots)

gd = ["## GENERATED by godot/dev/port/gen_mirror.py from the C# ride's members - do not edit by hand.",
      "## The ride's state as one packed array (slot i = the same member as BikePhysicsCs.gen.cs): how the GDScript",
      "## BikePhysics the game holds and the C# BikeSim that steps stay the same (docs/physics_port.md).",
      "class_name BikeMirror",
      "",
      f"const N := {N}",
      "",
      "static func pack(ph: BikePhysics) -> PackedFloat64Array:",
      "\tvar a := PackedFloat64Array()",
      "\ta.resize(N)"]
for i, (g, _, t) in enumerate(slots):
    if t == "bool":
        gd.append(f"\ta[{i}] = 1.0 if ph.{g} else 0.0")
    else:
        gd.append(f"\ta[{i}] = ph.{g}")
gd += ["\treturn a", "", "static func unpack(ph: BikePhysics, a: PackedFloat64Array) -> void:"]
for i, (g, _, t) in enumerate(slots):
    if t == "bool":
        gd.append(f"\tph.{g} = a[{i}] != 0.0")
    elif t == "long":
        gd.append(f"\tph.{g} = int(a[{i}])")
    else:
        gd.append(f"\tph.{g} = a[{i}]")
# (written as methods of BikePhysics itself, between markers at the end of bike_physics.gd: its own members are read /
# written directly, much faster than through another object; the translator skips _cs_* functions)
body = ["# --- generated by dev/port/gen_mirror.py (the C# step's state mirror): do not edit by hand ---   # (cs-hook)",
        "func _cs_out() -> PackedFloat64Array:", "\tvar a := PackedFloat64Array()", f"\ta.resize({N})"]
for i, (g, _, t) in enumerate(slots):
    body.append(f"\ta[{i}] = 1.0 if {g} else 0.0" if t == "bool" else f"\ta[{i}] = {g}")
body += ["\treturn a", "", "func _cs_in(a: PackedFloat64Array) -> void:"]
for i, (g, _, t) in enumerate(slots):
    if t == "bool":
        body.append(f"\t{g} = a[{i}] != 0.0")
    elif t == "long":
        body.append(f"\t{g} = int(a[{i}])")
    else:
        body.append(f"\t{g} = a[{i}]")
body.append("# --- end of generated mirror ---   # (cs-hook)")
bp = os.path.join(ROOT, "scripts/bike/bike_physics.gd")
src = open(bp, encoding="utf-8").read()
start = src.find("# --- generated by dev/port/gen_mirror.py")
if start >= 0:
    end = src.find("\n", src.find("# --- end of generated mirror ---", start))
    src = src[:start] + (src[end + 1:] if end >= 0 else "")
src = src.rstrip("\n") + "\n\n" + "\n".join(body) + "\n"
open(bp, "w", encoding="utf-8", newline="\n").write(src)
old_mirror = os.path.join(ROOT, "scripts/bike/bike_mirror.gd")
if os.path.exists(old_mirror):
    os.remove(old_mirror)

cs = ["// GENERATED by godot/dev/port/gen_mirror.py from the C# ride's members - do not edit by hand.",
      "// The ride's state as one packed array, slot for slot with scripts/bike/bike_mirror.gd.",
      "public partial class BikePhysicsCs",
      "{",
      f"\tpublic const int N = {N};",
      "",
      "\tprivate void Unpack(double[] a)",
      "\t{",
      "\t\tvar s = S;"]
for i, (_, c, t) in enumerate(slots):
    if t == "bool":
        cs.append(f"\t\ts.{c} = a[{i}] != 0.0;")
    elif t == "long":
        cs.append(f"\t\ts.{c} = (long)a[{i}];")
    else:
        cs.append(f"\t\ts.{c} = a[{i}];")
cs += ["\t}", "", "\tprivate void Pack(double[] a)", "\t{", "\t\tvar s = S;"]
for i, (_, c, t) in enumerate(slots):
    if t == "bool":
        cs.append(f"\t\ta[{i}] = s.{c} ? 1.0 : 0.0;")
    else:
        cs.append(f"\t\ta[{i}] = s.{c};")
cs += ["\t}", "}"]
open(os.path.join(ROOT, "scripts/bike/BikePhysicsCs.gen.cs"), "w", encoding="utf-8", newline="\n").write("\n".join(cs) + "\n")
print(f"GENMIRROR {N} slots")
