"""Writes scripts/bike/BikePhysicsCs.gen.cs: every BikeSim member as a Godot property under its GDScript name, so the
game (and the generic property walkers: replay snapshots, the playground's reset) reads the C# ride like bike_physics.gd.

python godot/dev/port/gen_adapter.py   (after gd2cs.py wrote dev/port/out/members.json)
"""
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
m = json.load(open(os.path.join(ROOT, "dev/port/out/members.json")))
KEYWORDS = {"base", "lock", "object", "string", "params", "out", "ref", "in", "is", "as", "new", "this", "case", "char",
            "decimal", "default", "delegate", "event", "fixed", "checked", "operator", "internal", "goto", "implicit",
            "explicit", "namespace", "using", "struct", "sizeof", "typeof", "unchecked", "unsafe", "virtual", "volatile",
            "void", "float", "double", "int", "long", "short", "byte", "uint", "ulong", "readonly", "sealed", "stackalloc",
            "switch", "throw", "try", "catch", "finally", "abstract", "const", "continue", "do", "else", "enum", "extern",
            "false", "for", "foreach", "if", "interface", "null", "override", "private", "protected", "public", "return",
            "static", "true", "while", "class", "bool", "break"}
# handled by hand in BikePhysicsCs.cs (engine links, inputs converted once, scratch)
HAND = {"host", "T", "sus", "crash_sim", "crash_K", "crash_RK", "prof", "_grip_noise", "_brk_noise", "_grip_rng",
        "_tapes_seen", "_wg_init"}


def cs(n):
    return "@" + n if n in KEYWORDS else n


out = ["// GENERATED by godot/dev/port/gen_adapter.py from the C# ride's members - do not edit by hand.",
       "// Every BikeSim member as a Godot property under its GDScript name (see BikePhysicsCs.cs).",
       "using Godot;",
       "using Runout.Sim;",
       "",
       "public partial class BikePhysicsCs",
       "{"]
for name, t in m["members"].items():
    if name in HAND:
        continue
    n = cs(name)
    if t in ("double", "long", "bool", "string"):
        out.append(f"\tpublic {t} {n} {{ get => S.{n}; set => S.{n} = value; }}")
    elif t == "V2":
        out.append(f"\tpublic Vector2 {n} {{ get => RideBridge.G(S.{n}); set => S.{n} = RideBridge.V(value); }}")
    elif t == "V3":
        out.append(f"\tpublic Vector3 {n} {{ get => RideBridge.G(S.{n}); set => S.{n} = RideBridge.V(value); }}")
    elif t == "GdDict":
        out.append(f"\tpublic Godot.Collections.Dictionary {n} {{ get => RideBridge.ToGodotCopy(S.{n}); set => S.{n} = value == null ? null : RideBridge.ToDict(value); }}")
    elif t == "List<double>":
        out.append(f"\tpublic Godot.Collections.Array {n} {{ get => RideBridge.ToArray(S.{n}); set => S.{n} = RideBridge.ToDoubles(value); }}")
    elif t == "List<object>":
        out.append(f"\tpublic Godot.Collections.Array {n} {{ get => RideBridge.ToArray(S.{n}); set => S.{n} = RideBridge.ToObjects(value); }}")
    elif t in ("double[]", "float[]"):
        out.append(f"\tpublic {t} {n} {{ get => S.{n}; set => S.{n} = value; }}")
    else:
        out.append(f"\t// {name}: {t} (not exposed)")
out.append("}")
open(os.path.join(ROOT, "scripts/bike/BikePhysicsCs.gen.cs"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(f"GENADAPTER {len(out) - 8} properties")
