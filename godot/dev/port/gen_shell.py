"""The ride is C# (godot/sim/BikeSim.cs): this writes its GDScript face's members and the state mirror from its fields.

  scripts/bike/bike_physics.gd       the members (every number / bool / int / Vector2 field of BikeSim) + _cs_out / _cs_in
                                     (between the "generated" markers at its end; everything above them is hand-written)
  scripts/bike/BikePhysicsCs.gen.cs  BikePhysicsCs.Unpack(a) / Pack(a): the same slots on the C# side

python godot/dev/port/gen_shell.py    after adding / removing / renaming a field in BikeSim.cs (or BikeSim.Manual.cs),
then `dotnet build`. A run with a stale shell stops with an error (the slot count is checked at start).
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SRC = [os.path.join(ROOT, "sim", "BikeSim.cs"), os.path.join(ROOT, "sim", "BikeSim.Manual.cs")]
GD = os.path.join(ROOT, "scripts", "bike", "bike_physics.gd")
CS = os.path.join(ROOT, "scripts", "bike", "BikePhysicsCs.gen.cs")
TYPES = {"double": "float", "long": "int", "bool": "bool", "V2": "Vector2"}
# fields at class level: `\t\tpublic [static ]TYPE name = ...;   // comment`
FIELD = re.compile(r"^\t\tpublic (static )?(readonly )?(\w+(?:<[^>]*>)?(?:\[\])?) (@?\w+)\s*(=|;)(.*)$")

fields = []   # (name, type, comment)
seen = set()
for path in SRC:
    for line in open(path, encoding="utf-8"):
        m = FIELD.match(line.rstrip("\n"))
        if not m or m.group(1) or m.group(2) or m.group(3) not in TYPES:
            continue
        name = m.group(4).lstrip("@")
        if name in seen:
            continue
        seen.add(name)
        com = ""
        c = m.group(6).find("//")
        if c >= 0:
            com = m.group(6)[c + 2:].strip()
        fields.append((name, m.group(3), com))
if not fields:
    sys.exit("GENSHELL: no fields found in sim/BikeSim.cs")

src = open(GD, encoding="utf-8").read()
start = src.find("# --- generated by dev/port/gen_shell.py")
hand = src if start < 0 else src[:start]
# members the hand-written part declares itself are left out of the generated list
hand_vars = set(re.findall(r"^var (\w+)", hand, re.M))
fields = [f for f in fields if f[0] not in hand_vars]

slots = []   # (gd expr, cs expr, kind)
for name, t, _ in fields:
    cs = name if not re.match(r"^(base|lock|object|string|params|out|ref|in|is|as|new|this|case|char|default|event|fixed|"
                               r"checked|operator|internal|goto|namespace|using|struct|sizeof|typeof|unchecked|unsafe|"
                               r"virtual|volatile|void|float|double|int|long|short|byte|readonly|sealed|switch|throw|"
                               r"try|catch|finally|abstract|const|continue|do|else|enum|extern|false|for|foreach|if|"
                               r"interface|null|override|private|protected|public|return|static|true|while|class|bool|"
                               r"break|decimal|delegate|explicit|implicit|uint|ulong|stackalloc)$", name) else "@" + name
    if t == "V2":
        slots.append((name + ".x", cs + ".x", "double"))
        slots.append((name + ".y", cs + ".y", "double"))
    else:
        slots.append((name, cs, t))
N = len(slots)

out = ["# --- generated by dev/port/gen_shell.py from sim/BikeSim.cs's fields: do not edit by hand ---",
       "# the C# ride's state, as this object's members (their values come from the C# ride: BikePhysicsCs.Defaults)"]
for name, t, com in fields:
    out.append(f"var {name}: {TYPES[t]}" + (f"   # {com}" if com else ""))
out += ["", f"const _CS_SLOTS := {N}", "",
        "func _cs_out() -> PackedFloat64Array:", "\tvar a := PackedFloat64Array()", f"\ta.resize({N})"]
for i, (g, _, t) in enumerate(slots):
    out.append(f"\ta[{i}] = 1.0 if {g} else 0.0" if t == "bool" else f"\ta[{i}] = {g}")
out += ["\treturn a", "", "func _cs_in(a: PackedFloat64Array) -> void:"]
for i, (g, _, t) in enumerate(slots):
    if t == "bool":
        out.append(f"\t{g} = a[{i}] != 0.0")
    elif t == "long":
        out.append(f"\t{g} = int(a[{i}])")
    else:
        out.append(f"\t{g} = a[{i}]")
out.append("# --- end of generated members ---")
open(GD, "w", encoding="utf-8", newline="\n").write(hand.rstrip("\n") + "\n\n" + "\n".join(out) + "\n")

cs = ["// GENERATED by godot/dev/port/gen_shell.py from sim/BikeSim.cs's fields - do not edit by hand.",
      "// The ride's state as one packed array, slot for slot with the generated end of scripts/bike/bike_physics.gd.",
      "public partial class BikePhysicsCs",
      "{",
      f"\tpublic const int N = {N};",
      "",
      "\tprivate void Unpack(double[] a)",
      "\t{",
      "\t\tvar s = S;"]
for i, (_, c, t) in enumerate(slots):
    if t == "bool":
        cs.append(f"\t\ts.{c} = a[{i}] != 0.0;")
    elif t == "long":
        cs.append(f"\t\ts.{c} = (long)a[{i}];")
    else:
        cs.append(f"\t\ts.{c} = a[{i}];")
cs += ["\t}", "", "\tprivate void Pack(double[] a)", "\t{", "\t\tvar s = S;"]
for i, (_, c, t) in enumerate(slots):
    cs.append(f"\t\ta[{i}] = s.{c} ? 1.0 : 0.0;" if t == "bool" else f"\t\ta[{i}] = s.{c};")
cs += ["\t}", "}"]
open(CS, "w", encoding="utf-8", newline="\n").write("\n".join(cs) + "\n")
print(f"GENSHELL {len(fields)} members, {N} slots")
